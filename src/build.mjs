// Cache version: bump when the demo pages or the stylesheets/scripts change, so no browser keeps a stale copy.
const V = '8';
// French pages open the French editions of the demos that have one (fr.html next to index.html).
const frDemos = (html) => html.replace(/(demos\/(?:naftal-b2b|marine-bot)\/)"/g, '$1fr.html"');
const bust = (html) => html
  .replace(/(demos\/(?:naftal-b2b|marine-bot)\/(?:fr\.html)?)"/g, `$1?v=${V}"`)
  .replace(/(assets\/[\w\/.-]+\.(?:css|js))"/g, `$1?v=${V}"`);

for (const lang of ['en', 'fr']) {
  const t = T[lang];
  const dir = lang === 'en' ? root : join(root, 'fr');
  await mkdir(dir, { recursive: true });
  const localise = lang === 'fr' ? frDemos : (html) => html;
  await writeFile(join(dir, 'index.html'), bust(localise(home(t))));
  await writeFile(join(dir, 'services.html'), bust(localise(services(t))));
  console.log(`${lang}: index.html, services.html`);
}
