const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const g = (name, cls = '') => `<svg class="h-glyph${cls ? ' ' + cls : ''}" aria-hidden="true"><use href="#g-${name}"></use></svg>`;
// {c:x} circled · {u:x} underlined · {k:x} key red · {em:x} italic voice (Instrument Serif)
const rich = (s) => esc(s)
  .replace(/\{c:([^}]+)\}/g, '<span class="mark" data-mark="circle">$1</span>')
  .replace(/\{u:([^}]+)\}/g, '<span class="mark mark--u" data-mark="underline">$1</span>')
  .replace(/\{k:([^}]+)\}/g, '<span class="kw">$1</span>')
  .replace(/\{em:([^}]+)\}/g, '<em>$1</em>');
