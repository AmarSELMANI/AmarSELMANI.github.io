// ------------------------------------------------------------------------ device mockups (real captures)
function mock(m, p, { alt = '', eager = false } = {}) {
  const img = (s, a = '') => `<img src="${p}${s.src}" alt="${esc(a)}" width="${s.w}" height="${s.h}" ${eager ? 'fetchpriority="high"' : 'loading="lazy"'} decoding="async"${s.pos ? ` style="object-position:${s.pos}"` : ''}>`;
  // each phone frame takes the shape of its own screenshot, so a phone layout is never cropped
  const phone = (s, cls = '') => `<div class="mock mock--phone${cls}" style="--ar:${s.w} / ${s.h}"><div class="mock__screen">${img(s)}</div></div>`;
  if (m.kind === 'phones') {
    return `<div class="mock-pair" role="img" aria-label="${esc(alt)}">${m.phones.map((ph) => phone(ph)).join('')}</div>`;
  }
  return `<div class="mock mock--browser" role="img" aria-label="${esc(alt)}">
          <div class="mock__bar" aria-hidden="true"><i></i><i></i><i></i><span class="mock__url">${esc(m.url || '')}</span></div>
          <div class="mock__screen">${img({ src: m.src, w: m.w, h: m.h, pos: m.pos })}</div>
          ${m.phone ? phone(m.phone, ' mock--over') : ''}${m.phones ? `<div class="mock__phones">${m.phones.map((ph) => phone(ph)).join('')}</div>` : ''}
        </div>`;
}

